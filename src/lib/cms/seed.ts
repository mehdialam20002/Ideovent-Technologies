/**
 * The canonical public host, resolved once for every consumer.
 *
 * Read in TWO runtimes: the Vite browser build (import.meta.env) and plain Node,
 * because scripts/generate-sitemap.mjs loads this same module to build
 * sitemap.xml. `import.meta.env` is undefined in Node, so touching it directly
 * throws there and the sitemap would silently keep the stale fallback.
 */
const CANONICAL_HOST: string = (() => {
  const viteEnv = (import.meta as unknown as { env?: Record<string, string> }).env;
  const nodeEnv = typeof process !== "undefined" ? process.env : undefined;
  const v = viteEnv?.VITE_PUBLIC_URL || nodeEnv?.VITE_PUBLIC_URL;
  return (v || "https://www.ideovent.in").replace(/\/$/, "");
})();

