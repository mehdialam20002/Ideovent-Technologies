// Base path prefix so local /public assets resolve under a subpath deploy (e.g. GitHub Pages).
const B = import.meta.env.BASE_URL; // "/" locally, "/Ideovent-Technologies/" on Pages

const slugify = (s: string) =>
  s.toLowerCase().trim().replace(/[^\w\s-]/g, "").replace(/\s+/g, "-").replace(/-+/g, "-").slice(0, 80);

/**
 * Resolve an asset path from the legacy JSON files against the deploy base.
 *
 * Blog covers used to be absolute https://i.postimg.cc/... URLs; they are now files in
 * public/blog-covers/ written as root-relative "/blog-covers/x.webp". A root-relative
 * path is wrong under a subpath deploy (GitHub Pages serves from
 * /Ideovent-Technologies/), so it is re-based here. Absolute URLs and data: URIs are
 * passed through untouched.
 */
const asset = (p?: string): string => {
  if (!p) return "";
  if (/^(https?:|data:|blob:)/.test(p)) return p;
  return `${B}${p.replace(/^\//, "")}`;
};

