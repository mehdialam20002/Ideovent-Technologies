#!/usr/bin/env node
/**
 * Regenerates ./data.generated.ts from public/demo/img/manifest.json.
 *
 *   node src/lib/demo/images/sync-manifest.mjs
 *
 * WHY A COPY. The photo FILES stay in public/demo/img/ (Vite serves them as
 * they are). The manifest DATA the pages need (sizes, alt, altHi, focal point)
 * must be importable by the build, and the full manifest also carries credits
 * and source URLs that no page needs. So this writes a trimmed, typed copy.
 * scripts/test-from-template.mjs fails when the copy and the manifest drift,
 * or when a listed file is missing on disk.
 *
 * Run it after adding, removing or re-cropping a photo in the manifest.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, "..", "..", "..", "..");
const manifest = JSON.parse(readFileSync(join(ROOT, "public", "demo", "img", "manifest.json"), "utf8"));

/** The compact record the site imports. Keep in step with StockPhotoData in ./index.ts. */
export function compact(p) {
  const sizes = [...p.sizes].sort((a, b) => b.w - a.w);
  const smallest = sizes[sizes.length - 1];
  const role = p.role || (p.id.startsWith("people/") ? "portrait" : /(^|\/)(c\d-)?hero-/.test(p.id) ? "hero" : "section");
  return {
    id: p.id,
    /* The canonical value a record stores: the smallest file, so an admin
       thumbnail is cheap. Any size's path resolves back to this entry. */
    src: smallest.src,
    role,
    category: p.category || "",
    ...(p.gender ? { gender: p.gender } : {}),
    suggestedFor: p.suggestedFor || [],
    sizes: sizes.map((s) => [s.w, s.h]),
    focal: [p.focal?.x ?? 0.5, p.focal?.y ?? 0.5],
    alt: p.alt,
    altHi: p.altHi,
  };
}

const rows = manifest.photos.map(compact);
const body = rows.map((r) => "  " + JSON.stringify(r)).join(",\n");
const out = `/* GENERATED by src/lib/demo/images/sync-manifest.mjs from
   public/demo/img/manifest.json. Do not edit by hand: edit the manifest and
   run the script. ${rows.length} photos. */

export const STOCK_PHOTO_DATA = [
${body},
] as const;
`;
writeFileSync(join(here, "data.generated.ts"), out);
console.log(`wrote ${rows.length} photos to src/lib/demo/images/data.generated.ts`);
